"""XMP measurement template (.xml) 동적 생성.

GUI export한 .xml format을 학습해 자동 생성.
Ellipse 중심·반경·measure type 인자화.

XMP_Template 구조 (핵심만):
- AreaClass class="OptisMapAreaTypeSurfaceEllipse"
  - X, Y: center (mm)
  - RX, RY: radius (mm)
  - Sampling: 측정 ray sampling
- MeasuresVector
  - Type: 8 = Flux (GUI 에서 export 한 .xml 그대로)
  - MeasureMagnitude, MeasureFunction: 0 (default)
"""

from __future__ import annotations
from pathlib import Path
from typing import Literal


MeasureType = Literal["Flux"]  # 향후 다른 type 추가 가능


def make_ellipse_flux_template(
    out_path: str | Path,
    center_x_mm: float = 0.0,
    center_y_mm: float = 0.0,
    rx_mm: float = 20.0,
    ry_mm: float = 20.0,
    sampling: int = 10000,
    grid_x_min_mm: float = -25.0,
    grid_x_max_mm: float = 25.0,
    grid_x_nb: int = 50,
    grid_y_min_mm: float = -25.0,
    grid_y_max_mm: float = 25.0,
    grid_y_nb: int = 50,
    name: str = "Area",
) -> Path:
    """XMP template (.xml) 생성.

    Args:
        out_path: 저장 경로 (.xml)
        center_x_mm, center_y_mm: ellipse 중심 (mm)
        rx_mm, ry_mm: ellipse 반경 (mm)
        sampling: measure sampling 수
        grid_*: XMP map grid (sensor 설정과 일치 권장)
        name: measure area 이름

    Returns:
        생성된 파일 path
    """
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    # GUI export .xml 구조 따름. default option은 같이 유지.
    # AreaClass + MeasureType=8(Flux)
    xml = f"""<?xml version="1.0" encoding="ISO-8859-1"?>
<XMP_Template>
<OptisMapType>3</OptisMapType>
<OptisValueType>0</OptisValueType>
<OptisUnitType>0</OptisUnitType>
<OptisIlluminanceType>0</OptisIlluminanceType>
<Comment>"Generated by make_template.py - Ellipse Flux measure"</Comment>
<OptisMap>
<XMin>{grid_x_min_mm}</XMin>
<XMax>{grid_x_max_mm}</XMax>
<XNb>{grid_x_nb}</XNb>
<YMin>{grid_y_min_mm}</YMin>
<YMax>{grid_y_max_mm}</YMax>
<YNb>{grid_y_nb}</YNb>
<FiniteDistanceSensorRadius>100</FiniteDistanceSensorRadius>
<RadAngularResolutionRadius>0.017453292519943295</RadAngularResolutionRadius>
<OptisMapExtended>
<OptisMapLayerType>0</OptisMapLayerType>
</OptisMapExtended>
</OptisMap>
<OptisMapOption>
<ColorMode>false</ColorMode>
<FalseColorMode>0</FalseColorMode>
<ReturnValueType>0</ReturnValueType>
<LevelMapping>0</LevelMapping>
<SurfaceAutomaticUpdate>true</SurfaceAutomaticUpdate>
<IsoCurves>false</IsoCurves>
<Filled>false</Filled>
<IsWhitePointLuminance>false</IsWhitePointLuminance>
<ViewAngles>false</ViewAngles>
<HorizontalFlip>false</HorizontalFlip>
<ShowRegulationTitle>false</ShowRegulationTitle>
<ShowRegulationSubtitle>false</ShowRegulationSubtitle>
<ShowRegulationSummary>false</ShowRegulationSummary>
<ShowRegulationRightSide>false</ShowRegulationRightSide>
<ShowRegulationLogo>false</ShowRegulationLogo>
<OverlapGrid>false</OverlapGrid>
<Visibility>false</Visibility>
<DisplayOptionSurface3D>false</DisplayOptionSurface3D>
<DisplayOptionSection2D>false</DisplayOptionSection2D>
<DisplayOptionSpectrum>false</DisplayOptionSpectrum>
<DisplayOptionColorimetricData>false</DisplayOptionColorimetricData>
<DisplayOptionColorimetricData3D>false</DisplayOptionColorimetricData3D>
<DisplayOptionProjectedColorimetricData3D>false</DisplayOptionProjectedColorimetricData3D>
<DisplayOptionCRI>false</DisplayOptionCRI>
<AxisUnit>millimetre</AxisUnit>
<ValueFormat>%g</ValueFormat>
<InterpolateValue>true</InterpolateValue>
<DrawDibAndRulerParameters>
<ShowRuler>false</ShowRuler>
<ShowRulerLeft>true</ShowRulerLeft>
<ShowRulerTop>true</ShowRulerTop>
<ShowRulerRight>true</ShowRulerRight>
<ShowRulerBottom>true</ShowRulerBottom>
<ShowRulerAxesOnCross>false</ShowRulerAxesOnCross>
<ColorAroundTheMap>6579300</ColorAroundTheMap>
<FillShape>false</FillShape>
<ShowPrimaryGraduation>true</ShowPrimaryGraduation>
<ShowSecondaryGraduation>true</ShowSecondaryGraduation>
<GraduationParameters>
<Decimals>2</Decimals>
</GraduationParameters>
<ShowPrimaryGrid>true</ShowPrimaryGrid>
<ShowSecondaryGrid>false</ShowSecondaryGrid>
<GridParameters>
<Automatic>false</Automatic>
<OriginX>0</OriginX>
<OriginY>0</OriginY>
<PrimaryStepX>10</PrimaryStepX>
<PrimaryStepY>10</PrimaryStepY>
<PrimaryGraduationNbX>0</PrimaryGraduationNbX>
<PrimaryGraduationNbY>0</PrimaryGraduationNbY>
<SecondaryGraduationNbX>9</SecondaryGraduationNbX>
<SecondaryGraduationNbY>9</SecondaryGraduationNbY>
</GridParameters>
<LinkCrossToGrid>false</LinkCrossToGrid>
<ShowTooltip>false</ShowTooltip>
<ShowFlux>true</ShowFlux>
<ShowMinimum>false</ShowMinimum>
<ShowMaximum>false</ShowMaximum>
</DrawDibAndRulerParameters>
<Filtering>
<FilteringValue>
<OptisFiltering>1</OptisFiltering>
<Parameter>
<Name>PassNumber</Name>
<Value>2</Value>
</Parameter>
</FilteringValue>
</Filtering>
<GridViewInReport>false</GridViewInReport>
<Description>""</Description>
<AutomotiveSignaling>
<Category>""</Category>
<GeographicalRegulationAreaAcronym>""</GeographicalRegulationAreaAcronym>
<Subtitle>""</Subtitle>
</AutomotiveSignaling>
<AreasVector>
<OptisMapAreaAndMeasures>
<AreaClass class="OptisMapAreaTypeSurfaceEllipse">
<OptisMapArea>
<Display>false</Display>
<Name>"{name}"</Name>
<ManipulatorMatrix Size="16">1.000000 0.000000e+00 0.000000e+00 0.000000e+00 0.000000e+00 1.000000 0.000000e+00 0.000000e+00 0.000000e+00 0.000000e+00 1.000000 0.000000e+00 0.000000e+00 0.000000e+00 0.000000e+00 1.000000</ManipulatorMatrix>
<OptisMapSurfaceEllipse>
<Sampling>{sampling}</Sampling>
<X>{center_x_mm}</X>
<Y>{center_y_mm}</Y>
<RX>{rx_mm}</RX>
<RY>{ry_mm}</RY>
</OptisMapSurfaceEllipse>
</OptisMapArea>
</AreaClass>
<MeasuresVector>
<OptisMapMeasure>
<MeasureMagnitude>0</MeasureMagnitude>
<MeasureFunction>0</MeasureFunction>
<Type>8</Type>
<UseThresholdMin>false</UseThresholdMin>
<UseThresholdMax>false</UseThresholdMax>
<ThresholdMin>0</ThresholdMin>
<ThresholdMax>0</ThresholdMax>
<RuleName>""</RuleName>
<RuleTargetGlobal>""</RuleTargetGlobal>
<RuleTargetMin>""</RuleTargetMin>
<RuleTargetMax>""</RuleTargetMax>
<RuleTargetMinSpec>""</RuleTargetMinSpec>
<RuleTargetMaxSpec>""</RuleTargetMaxSpec>
<IsTargetResultMin>false</IsTargetResultMin>
<IsTargetResultMax>false</IsTargetResultMax>
<IsTargetResultMinSpec>false</IsTargetResultMinSpec>
<IsTargetResultMaxSpec>false</IsTargetResultMaxSpec>
</OptisMapMeasure>
</MeasuresVector>
</OptisMapAreaAndMeasures>
</AreasVector>
<SelectedArea>0</SelectedArea>
<SelectedMeasure>0</SelectedMeasure>
</OptisMapOption>
</XMP_Template>
"""
    out_path.write_text(xml, encoding="iso-8859-1")
    return out_path


if __name__ == "__main__":
    # 예: 반경 20 mm 원형 영역의 광속
    p = make_ellipse_flux_template(
        out_path=Path(__file__).parent / "focal_plane_ellipse_r20_flux.xml",
        center_x_mm=0.0, center_y_mm=0.0,
        rx_mm=20.0, ry_mm=20.0,
        name="Focal_Plane_Bottom",
    )
    print(f"template 생성: {p}")
